# ---------------------------------------------------------------- 8. 광장 벤치 (온기)
def square_bench() -> Image.Image:
    """정면에서 내려다본 벤치: 등받이 판 2장 + 앉는 판 3장(노랑), 주철 다리·팔걸이(중립)."""
    n = 26
    rows = [".ss" + "." * n + "ss."]
    for ramp in ("4321", "4321"):                       # 등받이 판 2장
        rows += [".sS" + ch * n + "Ss." for ch in ramp]
    rows += ["sSSs" + "." * (n - 2) + "sSSs"]
    for ramp in ("432", "431", "421"):                   # 앉는 판 3장 (윗면이 넓게 보인다)
        rows += ["sS" + ch * (n + 2) + "Ss" for ch in ramp]
    rows += [".sS" + "." * n + "Ss."] * 2 + [".ss" + "." * n + "ss."]
    img = grid(rows, L(WARMTH), "square_bench")
    # 판 끝의 나뭇결 (어두운 점)
    px = img.load()
    from palette import rgba
    for x, y in ((8, 2), (19, 6), (12, 11), (23, 14), (6, 17)):
        px[x, y] = rgba("warmth-dark")
    return finish(img)


