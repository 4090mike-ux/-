def finish(img: Image.Image) -> Image.Image:
    """투명 여백 1px 을 두르고 외곽선."""
    box = img.getbbox()
    img = img.crop(box)
    pad = Image.new("RGBA", (img.width + 2, img.height + 2), (0, 0, 0, 0))
    paste(pad, img, 1, 1)
    return outline(pad)


def L(ramp: dict[str, str]) -> dict[str, str]:
    return {**NEUTRAL, **ramp}


