    top = """
        ..3..
        .343.
        ..2..
        .121.
    """
    c.stamp(top, L(LONGING), 8, 0)
    # 시계 몸통 (원), 바깥 테 = 그리움 램프
    c.ellipse(cx, cy, 9.5, 9.5, "longing-dark")
