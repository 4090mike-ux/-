# ---------------------------------------------------------------- 2. 별 화분 (온기)
def garden_pot() -> Image.Image:
    """위에서 비스듬히 본 별 모양 화분. 윗면 = 노란 테두리 + 흙, 옆면 = 노랑 어둡게."""
    W, H = 26, 24
    c = Canvas(W, H, None)
    cx, cy, R, r, squash, depth = 12.5, 8.0, 12.0, 5.6, 0.62, 7

    def star(ox: float, oy: float, rr: float, ri: float) -> list[tuple[int, int]]:
        pts = []
        for i in range(10):
            ang = -math.pi / 2 + i * math.pi / 5
            rad = rr if i % 2 == 0 else ri
            pts.append((round(ox + rad * math.cos(ang)), round(oy + rad * math.sin(ang) * squash)))
        return pts

    for d in range(depth, 0, -1):  # 옆면: 아래쪽일수록 어둡게
        c.poly(star(cx, cy + d, R, r), "warmth-dark" if d > depth - 3 else "warmth-mid")
    c.poly(star(cx, cy, R, r), "warmth-light")
    c.poly(star(cx, cy + 0.6, R - 2.4, r - 1.2), "warmth-mid")   # 테두리 안쪽 그늘
    c.poly(star(cx, cy + 1.0, R - 3.4, r - 1.9), "neutral-wood-dark")   # 흙
    # 흙 결
    for x, y in ((10, 9), (14, 8), (12, 10), (16, 10)):
        c.set(x, y, "neutral-shadow")
    # 윗면 하이라이트 (왼쪽 위 테두리)
    for x, y in ((12, 0), (12, 1), (11, 2), (10, 3), (4, 5), (5, 5), (6, 5), (7, 4)):
        if c.get(x, y):
            c.set(x, y, "warmth-highlight")
    # 새싹 (중립: 초록은 치유 색이라 쓰지 않는다)
    sprout = """
        KK...KK
        KMMKMMK
        .KMaMK.
        ..KaK..
        ...a...
    """
    c.stamp(sprout, NEUTRAL, 9, 2)
    return finish(c.to_image())


