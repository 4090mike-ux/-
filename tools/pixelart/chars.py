def _face_frame(points: dict[tuple[int, int], str]) -> Image.Image:
    from palette import rgba
    img = Image.new("RGBA", (FW, FH), CLEAR)
    px = img.load()
    for (x, y), ch in points.items():
        px[x, y] = rgba(FACE_LEGEND[ch])
    return img


def face_overlay(level: str) -> Image.Image:
    """96×32: down, left, right, up. up 은 뒤통수라 비어 있다."""
    down = _face_frame(FACE_DOWN[level])
    left = _face_frame(FACE_LEFT[level])
    up = Image.new("RGBA", (FW, FH), CLEAR)
    return sheet([[down, left, mirror(left), up]], FW, FH)


