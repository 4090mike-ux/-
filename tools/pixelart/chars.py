"""주인공·NPC 보행 시트와 NPC 얼굴 오버레이.

시트 규격 (docs/style/asset_manifest.md)
  프레임 24×32, 4열 × 4행 = 96×128
  행(위→아래): down, left, right, up      열: stand, stepA, stand, stepB
  발 = 프레임 바닥 중앙 (x 12, y 31). right 행은 left 행의 좌우 반전.

프레임 조립: 윗몸(머리+몸통) 격자 + 다리 격자. 걷는 프레임(stepA/B)은 윗몸이 1px 내려간다(보폭만큼 낮아짐).
격자는 '채우기'만 그리고 바깥 외곽선(neutral-ink)은 자동으로 두른다. 안쪽 선(눈, 팔과 몸 경계)만 K 로 직접 그린다.

NPC 는 머리가 모든 열에서 같은 자리에 있다(흔들림 없음). 그래서 얼굴 오버레이는 방향마다 한 프레임이면 된다.
"""
from __future__ import annotations

from PIL import Image

from sprite import CLEAR, grid, mirror, outline, paste, rows_of, sheet

FW, FH = 24, 32
FEET_ROW = 30  # 채우기의 마지막 줄. 31번 줄은 외곽선


def part(text: str, name: str) -> list[str]:
    """빈 줄은 무시한다(조각을 이어 붙일 때 생기는 줄바꿈). 투명한 줄은 '.' 24개로 쓴다."""
    rows = [r for r in rows_of(text) if r.strip()]
    for i, r in enumerate(rows):
        if len(r) != FW:
            raise ValueError(f"{name}: {i}번째 줄 너비 {len(r)} != {FW}: {r!r}")
    return rows


def frame(upper: list[str], legs: list[str], legend: dict[str, str], bob: int, name: str,
          upper_top: int = 0) -> Image.Image:
    img = Image.new("RGBA", (FW, FH), CLEAR)
    paste(img, grid(legs, legend, name + ".legs"), 0, FEET_ROW + 1 - len(legs))
    paste(img, grid(upper, legend, name + ".upper"), 0, upper_top + bob)
    return outline(img)


def walk_sheet(spec: dict, legend: dict[str, str], name: str, bob: bool = True) -> Image.Image:
    """spec[dir] = {"upper": [...], "upper_step": [...]?, "legs": (stand, stepA, stepB)}  dir ∈ down/left/up"""
    rows = []
    for d in ("down", "left", "up"):
        s = spec[d]
        up_stand = s["upper"]
        up_a = s.get("upper_a", up_stand)
        up_b = s.get("upper_b", up_a)
        b = 1 if bob else 0
        stand = frame(up_stand, s["legs"][0], legend, 0, f"{name}.{d}.stand")
        a = frame(up_a, s["legs"][1], legend, b, f"{name}.{d}.stepA")
        bb = frame(up_b, s["legs"][2], legend, b, f"{name}.{d}.stepB")
        rows.append([stand, a, stand, bb])
    left = rows[1]
    right = [mirror(f) for f in left]
    return sheet([rows[0], left, right, rows[2]], FW, FH)


